pub type Result<T> = anyhow::Result<T>;
pub fn id() -> String { uuid::Uuid::new_v4().simple().to_string() }
pub fn now() -> String { Utc::now().to_rfc3339_opts(chrono::SecondsFormat::Millis, true) }
pub fn hash(text: &str) -> String { format!("{:X}", Sha256::digest(text.as_bytes())) }
pub fn timezone(zone:&str)->Result<chrono_tz::Tz> {
    // Preserve the Windows timezone IDs accepted by the previous .NET version.
    // Mapping generated by Windows TimeZoneInfo.TryConvertWindowsIdToIanaId.
    static ZONES:LazyLock<std::collections::HashMap<String,String>>=LazyLock::new(||serde_json::from_str(include_str!("../windows-zones.json")).unwrap());
    Ok(ZONES.get(zone).map(String::as_str).unwrap_or(zone).parse()?)
}
pub fn today(zone: &str) -> Result<String> { Ok(Utc::now().with_timezone(&timezone(zone)?).format("%Y-%m-%d").to_string()) }
pub fn atomic_text(path: &Path, text: &str) -> Result<()> {
    if let Some(parent) = path.parent() { fs::create_dir_all(parent)?; }
    let temp = path.with_extension(format!("{}.tmp",id()));
    fs::write(&temp,text)?;
    let from:Vec<u16> = temp.as_os_str().to_string_lossy().encode_utf16().chain(Some(0)).collect();
    let to:Vec<u16> = path.as_os_str().to_string_lossy().encode_utf16().chain(Some(0)).collect();
    let result = unsafe { MoveFileExW(PCWSTR(from.as_ptr()), PCWSTR(to.as_ptr()), MOVEFILE_REPLACE_EXISTING|MOVEFILE_WRITE_THROUGH) };
    if result.is_err() { let _ = fs::remove_file(temp); }
    result.context("写入本机数据失败")
}
fn dpapi(bytes:&[u8], encrypt:bool) -> Result<Vec<u8>> {
    let input = CRYPT_INTEGER_BLOB { cbData:bytes.len() as u32,pbData:bytes.as_ptr() as *mut u8 };
    let mut output = CRYPT_INTEGER_BLOB::default();
    unsafe {
        if encrypt { CryptProtectData(&input, PCWSTR::null(),None,None,None,CRYPTPROTECT_UI_FORBIDDEN,&mut output)?; }
        else { CryptUnprotectData(&input,None,None,None,None,CRYPTPROTECT_UI_FORBIDDEN,&mut output)?; }
        let result=std::slice::from_raw_parts(output.pbData,output.cbData as usize).to_vec();
        let _=LocalFree(Some(HLOCAL(output.pbData as *mut _)));
        Ok(result)
    }
}
pub fn protect(text:&str) -> Result<String> { Ok(STANDARD.encode(dpapi(text.as_bytes(),true)?)) }
pub fn unprotect(text:&str) -> Result<String> { Ok(String::from_utf8(dpapi(&STANDARD.decode(text.trim())?,false)?)?) }
pub fn save_secret(path:&Path,text:&str) -> Result<()> { atomic_text(path,&protect(text)?) }
pub fn read_secret(path:&Path) -> Result<String> { unprotect(&fs::read_to_string(path)?) }
pub fn redact(text:&str)->String {
    static RULES:LazyLock<Vec<(regex::Regex,&str)>>=LazyLock::new(|| [
        (r"-----BEGIN [A-Z ]*PRIVATE KEY-----[\s\S]*?(?:-----END [A-Z ]*PRIVATE KEY-----|$)","[私钥已脱敏]"),
        (r"(?i)\b(?:sk-[a-z0-9_-]{12,}|gh[pousr]_[a-z0-9_]{15,}|github_pat_[a-z0-9_]{15,}|AKIA[A-Z0-9]{16})","[令牌已脱敏]"),
        (r"(?i)\b(?:Bearer|Basic)\s+[a-z0-9._~+/=-]+","[认证内容已脱敏]"),
        (r#"(?i)(["']?(?:api[_-]?key|access[_-]?token|refresh[_-]?token|password|passwd|client[_-]?secret|authorization)["']?\s*[:=]\s*)(?:["'][^"'\r\n]*["']|[^\s,;}]+)"#,"${1}[已脱敏]"),
        (r"(?i)(https?://)[^/\s:@]+:[^/\s@]+@","${1}[已脱敏]@")
    ].iter().map(|(p,r)|(regex::Regex::new(p).unwrap(),*r)).collect());
    RULES.iter().fold(text.to_string(),|value,(re,replacement)|re.replace_all(&value,*replacement).into_owned())
}

pub struct Store { pub root:PathBuf, connection:Mutex<Connection> }
impl Store {
    pub fn new(root:PathBuf)->Result<Self> {
        fs::create_dir_all(root.join("submissions"))?; fs::create_dir_all(root.join("reports"))?;
        let connection=Connection::open(root.join("department.db"))?;
        connection.execute_batch("PRAGMA journal_mode=WAL; PRAGMA synchronous=FULL; CREATE TABLE IF NOT EXISTS entities(kind TEXT NOT NULL,id TEXT NOT NULL,day TEXT NOT NULL,json TEXT NOT NULL,PRIMARY KEY(kind,id)); CREATE INDEX IF NOT EXISTS ix_entities_day ON entities(kind,day);")?;
        Ok(Self{root,connection:Mutex::new(connection)})
    }
    pub fn read<T>(&self,action:impl FnOnce(&Connection)->Result<T>)->Result<T> { let guard=self.connection.lock().map_err(|_|anyhow::anyhow!("数据库锁异常"))?; action(&guard) }
    pub fn write<T>(&self,action:impl FnOnce(&Connection)->Result<T>)->Result<T> {
        let mut conn=self.connection.lock().map_err(|_|anyhow::anyhow!("数据库锁异常"))?;
        let transaction=conn.transaction()?; let result=action(&transaction)?; transaction.commit()?; Ok(result)
    }
}
pub fn get(c:&Connection,kind:&str,id:&str)->Result<Option<Value>> {
    let text:Option<String>=c.query_row("SELECT json FROM entities WHERE kind=?1 AND id=?2",params![kind,id],|r|r.get(0)).optional()?;
    text.map(|v|serde_json::from_str(&v).map_err(Into::into)).transpose()
}
pub fn all(c:&Connection,kind:&str,day:Option<&str>)->Result<Vec<Value>> {
    let mut stmt=c.prepare("SELECT json FROM entities WHERE kind=?1 AND (?2 IS NULL OR day=?2) ORDER BY rowid")?;
    let records=stmt.query_map(params![kind,day],|r|r.get::<_,String>(0))?;
    records.map(|r|Ok(serde_json::from_str(&r?)?)).collect()
}
pub fn put(c:&Connection,kind:&str,id:&str,value:&Value,day:&str)->Result<()> { c.execute("INSERT INTO entities(kind,id,day,json) VALUES(?1,?2,?3,?4) ON CONFLICT(kind,id) DO UPDATE SET day=excluded.day,json=excluded.json",params![kind,id,day,serde_json::to_string(value)?])?; Ok(()) }
pub fn delete(c:&Connection,kind:&str,id:&str)->Result<()> { c.execute("DELETE FROM entities WHERE kind=?1 AND id=?2",params![kind,id])?; Ok(()) }

#[cfg(feature="leader")]
pub fn prompt(kind:&str)->Result<String> {
    use aes_gcm::{aead::Aead,Aes256Gcm,KeyInit,Nonce};
    let data:&[u8]=match kind {
        "personal" => include_bytes!(concat!(env!("OUT_DIR"),"/personal.v2.enc")),
        "department" => include_bytes!(concat!(env!("OUT_DIR"),"/department.v2.enc")),
        "extract" => include_bytes!(concat!(env!("OUT_DIR"),"/extract.v1.enc")),
        "merge" => include_bytes!(concat!(env!("OUT_DIR"),"/merge.v1.enc")),
        _ => anyhow::bail!("未知内置提示词：{kind}"),
    };
    let key=Sha256::digest(b"CodexDailyReport:leader-resource:v1:2026");
    let plain=Aes256Gcm::new_from_slice(&key).unwrap().decrypt(Nonce::from_slice(&data[..12]),&data[12..]).map_err(|_|anyhow::anyhow!("内置提示词资源无效"))?;
    Ok(String::from_utf8(plain)?)
}
